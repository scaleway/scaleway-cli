package login

import (
	"context"
	"encoding/base64"
	"encoding/json/v2"
	"fmt"
	"net/url"
	"reflect"
	"time"

	"github.com/scaleway/scaleway-cli/v2/core"
	initCommand "github.com/scaleway/scaleway-cli/v2/internal/namespaces/init"
	"github.com/scaleway/scaleway-cli/v2/internal/namespaces/login/webcallback"
	"github.com/scaleway/scaleway-sdk-go/api/account/v3"
	iam "github.com/scaleway/scaleway-sdk-go/api/iam/v1alpha1"
	"github.com/scaleway/scaleway-sdk-go/logger"
	"github.com/scaleway/scaleway-sdk-go/scw"
	"github.com/skratchdot/open-golang/open"
)

func GetCommands() *core.Commands {
	return core.NewCommands(loginCommand())
}

type loginArgs struct {
	Port           int
	PrintURL       bool
	ExpiresAt      *time.Time
	ProjectID      string
	OrganizationID string
}

func loginCommand() *core.Command {
	return &core.Command{
		Groups: []string{"config"},
		Short:  `Login to scaleway`,
		Long: `Start an interactive connection to scaleway to initialize the active profile of the config
A webpage will open while the CLI will wait for a response.
Once you connected to Scaleway, the profile should be configured.
`,
		Namespace:            "login",
		AllowAnonymousClient: true,
		ArgsType:             reflect.TypeFor[loginArgs](),
		ArgSpecs: core.ArgSpecs{
			{
				Name:  "port",
				Short: "The port number used to wait for browser's response",
			},
			{
				Name:  "expires-at",
				Short: "Expiration date of the API key (ISO 8601 or relative like +1y, +90d). Required when your organization enforces max-api-key-expiration-duration.",
			},
			{
				Name:  "project-id",
				Short: "Project ID to use for this login session for the API key created during login",
			},
			{
				Name:  "organization-id",
				Short: "Organization in which the API key is created, defaults to the default_organization_id of the profile",
			},
			{
				Name:  "print-url",
				Short: "Print the login url instead of trying to open the browser automatically",
			},
		},
		SeeAlsos: []*core.SeeAlso{
			{
				Short:   "Init profile manually",
				Command: "scw init",
			},
		},
		Run: func(ctx context.Context, argsI any) (any, error) {
			args := argsI.(*loginArgs)

			opts := []webcallback.Options(nil)
			if args.Port > 0 {
				opts = append(opts, webcallback.WithPort(args.Port))
			}

			wb := webcallback.New(opts...)
			err := wb.Start()
			if err != nil {
				return nil, err
			}

			callbackURL := fmt.Sprintf("http://localhost:%d/callback", wb.Port())

			organizationID := args.OrganizationID
			if organizationID == "" {
				organizationID = profileOrganizationID(ctx)
			}
			accountURL := buildLoginURL(callbackURL, organizationID)

			logger.Debugf("Web server started, waiting for callback on %s\n", callbackURL)

			if args.PrintURL {
				fmt.Println(accountURL)
			} else {
				err = open.Start(accountURL)
				if err != nil {
					logger.Warningf(
						"Failed to open web url, you may not have a default browser configured",
					)
					logger.Warningf("You can open it: %v", accountURL)
				}
			}

			fmt.Println("waiting for callback from browser...")
			token, err := wb.Wait(ctx)
			if err != nil {
				return nil, err
			}

			rawToken, err := base64.StdEncoding.DecodeString(token)
			if err != nil {
				return nil, err
			}

			tt := Token{}

			err = json.Unmarshal(rawToken, &tt)
			if err != nil {
				return nil, err
			}

			buildInfo := core.ExtractBuildInfo(ctx)
			client, err := scw.NewClient(
				scw.WithJWT(tt.Token),
				scw.WithUserAgent(buildInfo.GetUserAgent()),
			)
			if err != nil {
				return nil, err
			}

			api := iam.NewAPI(client)
			req := &iam.CreateAPIKeyRequest{
				UserID:      &tt.Jwt.AudienceID,
				Description: "Generated by the Scaleway CLI",
			}

			if args.ProjectID != "" {
				req.DefaultProjectID = &args.ProjectID
			}

			if args.ExpiresAt != nil {
				req.ExpiresAt = args.ExpiresAt
			}
			apiKey, err := api.CreateAPIKey(req)
			if err != nil {
				return nil, err
			}

			// Get the project to retrieve the organization ID
			accountAPI := account.NewProjectAPI(client)
			project, err := accountAPI.GetProject(&account.ProjectAPIGetProjectRequest{
				ProjectID: apiKey.DefaultProjectID,
			})
			if err != nil {
				return nil, err
			}

			if organizationID != "" && project.OrganizationID != organizationID {
				cleanErr := api.DeleteAPIKey(&iam.DeleteAPIKeyRequest{
					AccessKey: apiKey.AccessKey,
				})
				if cleanErr != nil {
					logger.Warningf("Failed to clean API key: %s\n", cleanErr.Error())
				}

				return nil, fmt.Errorf(
					"the API key was created in organization %s instead of %s, it has been deleted: log in to organization %s and retry",
					project.OrganizationID,
					organizationID,
					organizationID,
				)
			}

			resp, err := initCommand.Command().Run(ctx, &initCommand.Args{
				AccessKey:      apiKey.AccessKey,
				SecretKey:      *apiKey.SecretKey,
				ProjectID:      apiKey.DefaultProjectID,
				OrganizationID: project.OrganizationID,
				Region:         scw.RegionFrPar,
				Zone:           scw.ZoneFrPar1,
			})
			if err != nil {
				// Cleanup API Key if init failed
				logger.Warningf("Init failed, cleaning API key.\n")
				cleanErr := api.DeleteAPIKey(&iam.DeleteAPIKeyRequest{
					AccessKey: apiKey.AccessKey,
				})
				if cleanErr != nil {
					logger.Warningf("Failed to clean API key: %s\n", cleanErr.Error())
				}

				return nil, err
			}

			return resp, nil
		},
	}
}

// buildLoginURL returns the page opened by the browser to authenticate.
// The authenticate page uses the last organization session of
// account.scaleway.com: when an organization is targeted, the member login
// page of that organization is opened first, it then redirects to the
// authenticate page.
func buildLoginURL(callbackURL string, organizationID string) string {
	params := url.Values{}
	params.Add("redirectToUrl", callbackURL)
	authenticateURL := "https://account.scaleway.com/authenticate?" + params.Encode()
	if organizationID == "" {
		return authenticateURL
	}

	params = url.Values{}
	params.Add("organizationIdOrAlias", organizationID)
	params.Add("redirectToUrl", authenticateURL)

	return "https://account.scaleway.com/member-login?" + params.Encode()
}

// profileOrganizationID returns the default_organization_id of the profile
// being initialized, or an empty string.
func profileOrganizationID(ctx context.Context) string {
	config, err := scw.LoadConfigFromPath(core.ExtractConfigPath(ctx))
	if err != nil {
		return ""
	}
	profile, err := config.GetProfile(core.ExtractProfileName(ctx))
	if err != nil || profile.DefaultOrganizationID == nil {
		return ""
	}

	return *profile.DefaultOrganizationID
}

type Token struct {
	Jwt struct {
		AudienceID string    `json:"audienceId"`
		CreatedAt  time.Time `json:"createdAt"`
		ExpiresAt  time.Time `json:"expiresAt"`
		IP         string    `json:"ip"`
		IssuerID   string    `json:"issuerId"`
		Jti        string    `json:"jti"`
		UpdatedAt  time.Time `json:"updatedAt"`
		UserAgent  string    `json:"userAgent"`
	} `json:"jwt"`
	RenewToken string `json:"renewToken"`
	Token      string `json:"token"`
}
